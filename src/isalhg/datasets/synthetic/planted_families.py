"""Planted-family dataset — connected non-isomorphic hypergraphs with class labels.

Each *family* is a set of ``members_per_family`` structurally similar but
pairwise non-isomorphic connected hypergraphs generated by perturbing a common
seed motif.  The family index is the ``iso_class`` label (``IsoClassId``), so
the dataset provides a labelled corpus for clustering and kNN experiments
(A3/A6, PROPOSAL.md §4) whose ground truth is the planted family structure,
not isomorphism.

Generation contract:
- Seed motifs: provided explicitly via ``seeds`` or generated via rejection
  sampling (``random_hypergraph`` + ``is_connected()`` check).
- Additional members: obtained by applying ``n_edits`` independent random edits
  (``random_edit``) to the seed; rejected if the result is disconnected or
  isomorphic to any existing family member (fingerprint dedup).

Domain constraint D-CONN1 (DECISIONS.md 2026-07-09, PI-resolved): the
article's metric-space domain is *connected* hypergraphs.  This module is the
sole point of enforcement — the shared ``random_hypergraph`` helper and
``random_edit`` make no connectivity guarantee; ``is_connected()`` is checked
here on every accepted item.

Restriction: Python stdlib + ``isalhg.core`` + ``isalhg.datasets`` only.
The iso backend import is deferred inside ``_build()`` so this module is
importable without ``isalhg.iso_backends`` on the path.
"""

from __future__ import annotations

import logging
import random
from collections.abc import Iterator
from typing import Any

from isalhg.core.sparse_hypergraph import SparseHypergraph, random_edit
from isalhg.datasets.base import HypergraphDataset
from isalhg.datasets.registry import register_dataset
from isalhg.datasets.schemas import DatasetItem, DatasetMetadata, LabelVocabulary
from isalhg.datasets.synthetic._random_hg import random_hypergraph
from isalhg.types import DatasetName, Seed

logger = logging.getLogger(__name__)

# Prime stride keeps each family's PRNG stream independent.
_FAMILY_STRIDE = 999_983


def _resolve_backend(name: str) -> Any:
    """Lazy import of the iso backend by name."""
    from isalhg.iso_backends.registry import get_backend  # deferred

    return get_backend(name)


class PlantedFamilyDataset(HypergraphDataset):
    """Connected non-isomorphic hypergraphs organised into planted families.

    Each family contributes ``members_per_family`` hypergraphs to the corpus.
    All items in a family share the same ``iso_class`` (the 0-based family
    index) but are pairwise non-isomorphic.  Downstream experiments use the
    family index as the class label to evaluate clustering (ARI vs planted
    labels) and kNN accuracy.

    Parameters
    ----------
    seeds : list[SparseHypergraph] | None, optional
        Explicit seed motifs, one per family.  When provided,
        ``len(seeds)`` determines the number of families, and all seeds must
        be connected (checked at construction time).  When ``None``, seeds are
        generated randomly using ``n_families``, ``n_nodes``, ``k``,
        ``n_edges``, and ``seed_value``.  Default ``None``.
    members_per_family : int, optional
        Total members per family (including the seed itself).  Default ``3``.
    n_edits : int, optional
        Number of independent random edits applied to the seed motif to
        generate each non-seed member.  Larger values increase structural
        dissimilarity within the family.  Default ``2``.
    max_retries : int, optional
        Maximum rejection-sampling attempts per member.  Default ``200``.
    seed_value : int, optional
        Master random seed.  Family ``f`` uses ``seed_value + f * 999_983``
        for its PRNG stream.  Default ``0``.
    dedup_backend : str, optional
        Name of the iso backend used for non-iso deduplication (must be
        registered in ``iso_backends.registry``).  Default ``"isalhg"``
        (tie-complete canonical encoder — exact iso test).
    n_families : int, optional
        Number of families when ``seeds=None``.  Ignored when seeds are
        provided explicitly.  Default ``4``.
    n_nodes : int, optional
        Vertex count for randomly-generated seed motifs (``seeds=None``).
        Default ``6``.
    k : int, optional
        Maximum hyperedge arity for randomly-generated seeds.  Default ``3``.
    n_edges : int, optional
        Edge-insertion attempts for random seed generation.  Default ``5``.
    """

    def __init__(
        self,
        *,
        seeds: list[SparseHypergraph] | None = None,
        members_per_family: int = 3,
        n_edits: int = 2,
        max_retries: int = 200,
        seed_value: int = 0,
        dedup_backend: str = "isalhg",
        # Parameters for auto-generating seeds when seeds=None:
        n_families: int = 4,
        n_nodes: int = 6,
        k: int = 3,
        n_edges: int = 5,
    ) -> None:
        if members_per_family < 1:
            raise ValueError(f"members_per_family must be >= 1, got {members_per_family}")
        if n_edits < 1:
            raise ValueError(f"n_edits must be >= 1, got {n_edits}")
        if max_retries < 1:
            raise ValueError(f"max_retries must be >= 1, got {max_retries}")

        self._members_per_family = members_per_family
        self._n_edits = n_edits
        self._max_retries = max_retries
        self._seed_value: int = int(seed_value)
        self._dedup_backend = dedup_backend

        # Auto-generation parameters (only used when seeds is None)
        self._n_families_default = n_families
        self._n_nodes = n_nodes
        self._k = k
        self._n_edges = n_edges

        # Resolve seed motifs (explicit or auto-generated)
        if seeds is not None:
            for i, H in enumerate(seeds):
                if not H.is_connected():
                    raise ValueError(f"seeds[{i}] is not connected")
            self._seeds: list[SparseHypergraph] = list(seeds)
        else:
            self._seeds = self._generate_seeds(n_families)

        self._items: list[DatasetItem] = self._build()
        self._metadata: DatasetMetadata = self._make_metadata()

    # ------------------------------------------------------------------
    # Internal builders
    # ------------------------------------------------------------------

    def _generate_seeds(self, n_families: int) -> list[SparseHypergraph]:
        """Auto-generate connected seed motifs via rejection sampling."""
        if n_families < 1:
            raise ValueError(f"n_families must be >= 1, got {n_families}")
        if self._n_nodes < 2:
            raise ValueError(f"n_nodes must be >= 2, got {self._n_nodes}")
        if self._k < 2:
            raise ValueError(f"k must be >= 2, got {self._k}")

        seeds: list[SparseHypergraph] = []
        for fam_idx in range(n_families):
            rng = random.Random(self._seed_value + fam_idx * _FAMILY_STRIDE)
            motif = self._draw_connected(rng, fam_idx)
            seeds.append(motif)
        return seeds

    def _draw_connected(self, rng: random.Random, family_idx: int) -> SparseHypergraph:
        """Draw a random connected hypergraph; raise on exhaustion."""
        for attempt in range(self._max_retries):
            H = random_hypergraph(
                n_nodes=self._n_nodes,
                n_edges=self._n_edges,
                arity_range=(2, self._k),
                rng=rng,
            )
            if H.is_connected():
                return H
            logger.debug("family %d seed attempt %d disconnected; retrying", family_idx, attempt)
        raise RuntimeError(
            f"exhausted {self._max_retries} attempts generating a connected seed"
            f" for family {family_idx}"
            f" (n_nodes={self._n_nodes}, n_edges={self._n_edges}, k={self._k})"
        )

    def _build(self) -> list[DatasetItem]:
        backend = _resolve_backend(self._dedup_backend)
        items: list[DatasetItem] = []

        for fam_idx, seed_motif in enumerate(self._seeds):
            # Each family gets its own PRNG stream for perturbation.
            rng = random.Random(self._seed_value + fam_idx * _FAMILY_STRIDE)

            family_hgs: list[SparseHypergraph] = [seed_motif]
            family_fps: set[bytes] = {backend.fingerprint(seed_motif)}

            while len(family_hgs) < self._members_per_family:
                needed = len(family_hgs)
                found = False
                for attempt in range(self._max_retries):
                    # Apply n_edits independent random edits to the seed.
                    current: SparseHypergraph = seed_motif
                    for _ in range(self._n_edits):
                        current, _ = random_edit(current, rng)
                    # Empty hypergraph (n=0) is vacuously connected but outside the
                    # d_I domain (DegenerateHypergraphError from fingerprint); skip.
                    if current.n_nodes == 0:
                        logger.debug(
                            "family %d member %d attempt %d empty (n=0); retrying",
                            fam_idx,
                            needed,
                            attempt,
                        )
                        continue
                    if not current.is_connected():
                        logger.debug(
                            "family %d member %d attempt %d disconnected; retrying",
                            fam_idx,
                            needed,
                            attempt,
                        )
                        continue
                    # Arity gate: add_incidence can grow a hyperedge past k, violating
                    # Σ_HG(k) membership and causing IsalHGError from the C++ encoder
                    # when arity exceeds K_MAX=10 (sparse_hypergraph.py:462 — filtering
                    # is the caller's responsibility, not the edit ops').
                    if current.n_edges > 0 and max(len(e) for e in current.hyperedges()) > self._k:
                        logger.debug(
                            "family %d member %d attempt %d arity > k=%d; retrying",
                            fam_idx,
                            needed,
                            attempt,
                            self._k,
                        )
                        continue
                    fp = backend.fingerprint(current)
                    if fp in family_fps:
                        logger.debug(
                            "family %d member %d attempt %d iso-duplicate; retrying",
                            fam_idx,
                            needed,
                            attempt,
                        )
                        continue
                    family_hgs.append(current)
                    family_fps.add(fp)
                    found = True
                    break

                if not found:
                    raise RuntimeError(
                        f"exhausted {self._max_retries} attempts generating"
                        f" member {needed} of family {fam_idx}"
                        f" (n_edits={self._n_edits},"
                        f" seed_value={self._seed_value})"
                    )

            for member_idx, H in enumerate(family_hgs):
                item_id = f"f{fam_idx:04d}_m{member_idx:04d}"
                items.append(
                    DatasetItem(
                        item_id=item_id,
                        hypergraph=H,
                        iso_class=None,
                        extra={
                            "class_label": fam_idx,
                            "family_index": fam_idx,
                            "member_index": member_idx,
                            "is_seed": member_idx == 0,
                        },
                    )
                )

        return items

    def _make_metadata(self) -> DatasetMetadata:
        n_nodes_vals = [item.hypergraph.n_nodes for item in self._items]
        n_families = len(self._seeds)
        return DatasetMetadata(
            name="planted_families",
            n_items=len(self._items),
            arity_range=(2, self._k),
            n_nodes_range=(min(n_nodes_vals), max(n_nodes_vals)),
            has_iso_labels=False,
            source=(
                f"PlantedFamilyDataset(n_families={n_families},"
                f" members_per_family={self._members_per_family},"
                f" n_edits={self._n_edits},"
                f" seed_value={self._seed_value})"
            ),
            label_vocabulary=LabelVocabulary.trivial(),
        )

    # ------------------------------------------------------------------
    # HypergraphDataset ABC
    # ------------------------------------------------------------------

    @property
    def name(self) -> DatasetName:
        return "planted_families"

    @property
    def metadata(self) -> DatasetMetadata:
        return self._metadata

    def __iter__(self) -> Iterator[DatasetItem]:
        return iter(self._items)

    def __len__(self) -> int:
        return len(self._items)

    def seed(self, seed: Seed) -> PlantedFamilyDataset:
        """Return a copy re-seeded with ``seed``."""
        return PlantedFamilyDataset(
            seeds=self._seeds,
            members_per_family=self._members_per_family,
            n_edits=self._n_edits,
            max_retries=self._max_retries,
            seed_value=int(seed),
            dedup_backend=self._dedup_backend,
        )


def _factory(params: dict[str, Any]) -> PlantedFamilyDataset:
    return PlantedFamilyDataset(**params)


register_dataset("planted_families", _factory)
